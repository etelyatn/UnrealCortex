TSharedPtr<FJsonObject> FCortexGraphRetargetSite::ToJson() const
{
	TSharedPtr<FJsonObject> Json = MakeShared<FJsonObject>();
	Json->SetStringField(TEXT("graph_guid"), GraphGuid);
	Json->SetStringField(TEXT("subgraph_path"), SubgraphPath);
	Json->SetStringField(TEXT("node_guid"), NodeGuid);
	Json->SetStringField(TEXT("node_class_path"), NodeClassPath);
	Json->SetStringField(TEXT("kind"), Kind);
	TArray<TSharedPtr<FJsonValue>> PinValues;
	for (const FCortexGraphRetargetPin& Pin : Pins)
	{
		TSharedPtr<FJsonObject> PinJson = MakeShared<FJsonObject>();
		PinJson->SetStringField(TEXT("name"), Pin.Name);
		PinJson->SetStringField(TEXT("direction"), DirectionName(Pin.Direction));
		PinJson->SetStringField(TEXT("signature"), Pin.Signature);
		if (!Pin.MapsTo.IsEmpty())
		{
			PinJson->SetStringField(TEXT("maps_to"), Pin.MapsTo);
		}
		TArray<TSharedPtr<FJsonValue>> LinkValues;
		for (const FCortexGraphRetargetLink& Link : Pin.Links)
		{
			TSharedPtr<FJsonObject> LinkJson = MakeShared<FJsonObject>();
			LinkJson->SetStringField(TEXT("node_guid"), Link.NodeGuid);
			LinkJson->SetStringField(TEXT("pin"), Link.Pin);
			LinkValues.Add(MakeShared<FJsonValueObject>(LinkJson));
		}
		PinJson->SetArrayField(TEXT("links"), LinkValues);
		PinValues.Add(MakeShared<FJsonValueObject>(PinJson));
	}
	Json->SetArrayField(TEXT("pins"), PinValues);
	if (!Blocked.IsEmpty())
	{
		Json->SetStringField(TEXT("blocked"), Blocked);
	}
	if (!ReplacementGuid.IsEmpty())
	{
		Json->SetStringField(TEXT("replacement_guid"), ReplacementGuid);
	}
	return Json;
}

bool FCortexGraphRetargetSite::FromJson(const TSharedPtr<FJsonObject>& Source, FCortexGraphRetargetSite& OutSite, FCortexCommandResult& OutError)
{
	OutSite = FCortexGraphRetargetSite();
	if (!Source.IsValid()
		|| !FCortexGraphPatchOps::HasOnlyFields(Source,
			{ TEXT("graph_guid"), TEXT("subgraph_path"), TEXT("node_guid"), TEXT("node_class_path"), TEXT("kind"), TEXT("pins"),
				TEXT("blocked"), TEXT("replacement_guid") },
			OutError, TEXT("migration.sites entry")))
	{
		if (!Source.IsValid())
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("every migration.sites entry must be an object"));
		}
		return false;
	}
	const TArray<TSharedPtr<FJsonValue>>* PinValues = nullptr;
	if (!Source->TryGetStringField(TEXT("graph_guid"), OutSite.GraphGuid)
		|| !Source->TryGetStringField(TEXT("node_guid"), OutSite.NodeGuid)
		|| !Source->TryGetStringField(TEXT("node_class_path"), OutSite.NodeClassPath)
		|| !Source->TryGetStringField(TEXT("kind"), OutSite.Kind)
		|| !Source->TryGetArrayField(TEXT("pins"), PinValues) || !PinValues)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
			TEXT("every migration.sites entry needs graph_guid, node_guid, node_class_path, kind and pins"));
		return false;
	}
	Source->TryGetStringField(TEXT("subgraph_path"), OutSite.SubgraphPath);
	Source->TryGetStringField(TEXT("blocked"), OutSite.Blocked);
	Source->TryGetStringField(TEXT("replacement_guid"), OutSite.ReplacementGuid);
	for (const TSharedPtr<FJsonValue>& PinValue : *PinValues)
	{
		const TSharedPtr<FJsonObject> PinJson = PinValue.IsValid() ? PinValue->AsObject() : nullptr;
		if (!PinJson.IsValid()
			|| !FCortexGraphPatchOps::HasOnlyFields(PinJson,
				{ TEXT("name"), TEXT("direction"), TEXT("signature"), TEXT("maps_to"), TEXT("links") }, OutError, TEXT("migration.sites pin")))
		{
			if (OutError.ErrorCode.IsEmpty())
			{
				OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("every migration.sites pin must be an object"));
			}
			return false;
		}
		FCortexGraphRetargetPin Pin;
		FString DirectionText;
		const TArray<TSharedPtr<FJsonValue>>* LinkValues = nullptr;
		if (!PinJson->TryGetStringField(TEXT("name"), Pin.Name)
			|| !PinJson->TryGetStringField(TEXT("direction"), DirectionText) || !ParseDirection(DirectionText, Pin.Direction)
			|| !PinJson->TryGetStringField(TEXT("signature"), Pin.Signature)
			|| !PinJson->TryGetArrayField(TEXT("links"), LinkValues) || !LinkValues)
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
				TEXT("every migration.sites pin needs name, direction (input|output), signature and links"));
			return false;
		}
		PinJson->TryGetStringField(TEXT("maps_to"), Pin.MapsTo);
		for (const TSharedPtr<FJsonValue>& LinkValue : *LinkValues)
		{
			const TSharedPtr<FJsonObject> LinkJson = LinkValue.IsValid() ? LinkValue->AsObject() : nullptr;
			FCortexGraphRetargetLink Link;
			if (!LinkJson.IsValid()
				|| !FCortexGraphPatchOps::HasOnlyFields(LinkJson, { TEXT("node_guid"), TEXT("pin") }, OutError, TEXT("migration.sites link"))
				|| !LinkJson->TryGetStringField(TEXT("node_guid"), Link.NodeGuid) || !LinkJson->TryGetStringField(TEXT("pin"), Link.Pin))
			{
				if (OutError.ErrorCode.IsEmpty())
				{
					OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
						TEXT("every migration.sites link needs node_guid and pin"));
				}
				return false;
			}
			Pin.Links.Add(MoveTemp(Link));
		}
		OutSite.Pins.Add(MoveTemp(Pin));
	}
	return true;
}

FString FCortexGraphRetargetSite::Key() const
{
	FCortexGraphRetargetSite Sorted = *this;
	Sorted.Pins.Sort(PinLess);
	FString Out = FString::Printf(TEXT("%s|%s|%s|%s|%s|blocked=%s|replacement=%s"),
		*Sorted.GraphGuid, *Sorted.SubgraphPath, *Sorted.NodeGuid, *Sorted.NodeClassPath, *Sorted.Kind, *Sorted.Blocked, *Sorted.ReplacementGuid);
	for (FCortexGraphRetargetPin& Pin : Sorted.Pins)
	{
		Pin.Links.Sort(LinkLess);
		Out += FString::Printf(TEXT("\n pin %s|dir=%d|%s|maps=%s"), *Pin.Name, Pin.Direction, *Pin.Signature, *Pin.MapsTo);
		for (const FCortexGraphRetargetLink& Link : Pin.Links)
		{
			Out += FString::Printf(TEXT("\n  link %s.%s"), *Link.NodeGuid, *Link.Pin);
		}
	}
	return Out;
}

TSharedPtr<FJsonObject> FCortexGraphMigrationRetargetPlan::ToJson() const
{
	TSharedPtr<FJsonObject> Json = MakeShared<FJsonObject>();
	Json->SetStringField(TEXT("op"), Op);
	Json->SetStringField(TEXT("from_owner"), FromOwner);
	Json->SetStringField(TEXT("from_function"), FromFunction);
	Json->SetStringField(TEXT("to_owner"), ToOwner);
	Json->SetStringField(TEXT("to_function"), ToFunction);
	Json->SetStringField(TEXT("mode"), Mode);
	Json->SetNumberField(TEXT("scanned_nodes"), ScannedNodes);
	TArray<TSharedPtr<FJsonValue>> MapValues;
	for (const FCortexGraphRetargetPinMapping& Entry : PinMap)
	{
		TSharedPtr<FJsonObject> EntryJson = MakeShared<FJsonObject>();
		EntryJson->SetStringField(TEXT("from_pin"), Entry.FromPin);
		EntryJson->SetStringField(TEXT("to_pin"), Entry.ToPin);
		MapValues.Add(MakeShared<FJsonValueObject>(EntryJson));
	}
	Json->SetArrayField(TEXT("pin_map"), MapValues);
	TArray<TSharedPtr<FJsonValue>> SiteValues;
	for (const FCortexGraphRetargetSite& Site : Sites)
	{
		SiteValues.Add(MakeShared<FJsonValueObject>(Site.ToJson()));
	}
	Json->SetArrayField(TEXT("sites"), SiteValues);
	TArray<TSharedPtr<FJsonValue>> GraphValues;
	for (const FCortexGraphRetargetGraph& Graph : Graphs)
	{
		TSharedPtr<FJsonObject> GraphJson = MakeShared<FJsonObject>();
		GraphJson->SetStringField(TEXT("graph_guid"), Graph.GraphGuid);
		GraphJson->SetStringField(TEXT("subgraph_path"), Graph.SubgraphPath);
		GraphJson->SetNumberField(TEXT("node_count"), Graph.NodeCount);
		GraphJson->SetStringField(TEXT("expected_node_digest"), Graph.ExpectedNodeDigest);
		GraphValues.Add(MakeShared<FJsonValueObject>(GraphJson));
	}
	Json->SetArrayField(TEXT("graphs"), GraphValues);
	TArray<TSharedPtr<FJsonValue>> PreservationValues;
	for (const FCortexGraphTransferPreservation& Preservation : Preservations)
	{
		TSharedPtr<FJsonObject> PreservationJson = MakeShared<FJsonObject>();
		PreservationJson->SetStringField(TEXT("label"), Preservation.Label);
		PreservationJson->SetStringField(TEXT("graph_guid"), Preservation.GraphGuid);
		PreservationJson->SetStringField(TEXT("capture"), Preservation.Capture);
		PreservationJson->SetArrayField(TEXT("excluded_guids"), StringValues(Preservation.ExcludedGuids));
		PreservationValues.Add(MakeShared<FJsonValueObject>(PreservationJson));
	}
	Json->SetArrayField(TEXT("preservations"), PreservationValues);
	return Json;
}

bool FCortexGraphMigrationRetargetPlan::FromJson(
	const TSharedPtr<FJsonObject>& Source, FCortexGraphMigrationRetargetPlan& OutPlan, FCortexCommandResult& OutError)
{
	OutPlan = FCortexGraphMigrationRetargetPlan();
	OutError = FCortexCommandResult();
	const TArray<TSharedPtr<FJsonValue>>* MapValues = nullptr;
	const TArray<TSharedPtr<FJsonValue>>* SiteValues = nullptr;
	const TArray<TSharedPtr<FJsonValue>>* GraphValues = nullptr;
	const TArray<TSharedPtr<FJsonValue>>* PreservationValues = nullptr;
	double ScannedValue = 0;
	if (!Source.IsValid()
		|| !Source->TryGetStringField(TEXT("op"), OutPlan.Op) || OutPlan.Op != RetargetOpName
		|| !Source->TryGetStringField(TEXT("from_owner"), OutPlan.FromOwner)
		|| !Source->TryGetStringField(TEXT("from_function"), OutPlan.FromFunction)
		|| !Source->TryGetStringField(TEXT("to_owner"), OutPlan.ToOwner)
		|| !Source->TryGetStringField(TEXT("to_function"), OutPlan.ToFunction)
		|| !Source->TryGetStringField(TEXT("mode"), OutPlan.Mode)
		|| !Source->TryGetNumberField(TEXT("scanned_nodes"), ScannedValue)
		|| !Source->TryGetArrayField(TEXT("pin_map"), MapValues) || !MapValues
		|| !Source->TryGetArrayField(TEXT("sites"), SiteValues) || !SiteValues
		|| !Source->TryGetArrayField(TEXT("graphs"), GraphValues) || !GraphValues
		|| !Source->TryGetArrayField(TEXT("preservations"), PreservationValues) || !PreservationValues)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation, TEXT("prepared retarget_calls plan is incomplete"));
		return false;
	}
	OutPlan.ScannedNodes = static_cast<int32>(ScannedValue);
	Source->TryGetBoolField(TEXT("awaiting_approval"), OutPlan.bAwaitingApproval);
	for (const TSharedPtr<FJsonValue>& Value : *MapValues)
	{
		const TSharedPtr<FJsonObject> EntryJson = Value.IsValid() ? Value->AsObject() : nullptr;
		FCortexGraphRetargetPinMapping Entry;
		if (!EntryJson.IsValid() || !EntryJson->TryGetStringField(TEXT("from_pin"), Entry.FromPin) || !EntryJson->TryGetStringField(TEXT("to_pin"), Entry.ToPin))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation, TEXT("prepared retarget_calls plan has an invalid pin_map entry"));
			return false;
		}
		OutPlan.PinMap.Add(MoveTemp(Entry));
	}
	for (const TSharedPtr<FJsonValue>& Value : *SiteValues)
	{
		FCortexGraphRetargetSite Site;
		if (!FCortexGraphRetargetSite::FromJson(Value.IsValid() ? Value->AsObject() : nullptr, Site, OutError))
		{
			return false;
		}
		OutPlan.Sites.Add(MoveTemp(Site));
	}
	for (const TSharedPtr<FJsonValue>& Value : *GraphValues)
	{
		const TSharedPtr<FJsonObject> GraphJson = Value.IsValid() ? Value->AsObject() : nullptr;
		FCortexGraphRetargetGraph Graph;
		double CountValue = 0;
		if (!GraphJson.IsValid()
			|| !GraphJson->TryGetStringField(TEXT("graph_guid"), Graph.GraphGuid)
			|| !GraphJson->TryGetStringField(TEXT("subgraph_path"), Graph.SubgraphPath)
			|| !GraphJson->TryGetNumberField(TEXT("node_count"), CountValue)
			|| !GraphJson->TryGetStringField(TEXT("expected_node_digest"), Graph.ExpectedNodeDigest))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation, TEXT("prepared retarget_calls plan has an invalid graph entry"));
			return false;
		}
		Graph.NodeCount = static_cast<int32>(CountValue);
		OutPlan.Graphs.Add(MoveTemp(Graph));
	}
	for (const TSharedPtr<FJsonValue>& Value : *PreservationValues)
	{
		const TSharedPtr<FJsonObject> PreservationJson = Value.IsValid() ? Value->AsObject() : nullptr;
		FCortexGraphTransferPreservation Preservation;
		if (!PreservationJson.IsValid()
			|| !PreservationJson->TryGetStringField(TEXT("label"), Preservation.Label)
			|| !PreservationJson->TryGetStringField(TEXT("graph_guid"), Preservation.GraphGuid)
			|| !PreservationJson->TryGetStringField(TEXT("capture"), Preservation.Capture)
			|| !ReadStrings(PreservationJson, TEXT("excluded_guids"), Preservation.ExcludedGuids))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation, TEXT("prepared retarget_calls plan has an invalid preservation contract"));
			return false;
		}
		OutPlan.Preservations.Add(MoveTemp(Preservation));
	}
	return true;
}

bool FCortexGraphRetargetOps::ClassifySite(
	const UEdGraphNode* Node,
	const UClass* FromOwner,
	const FString& FromFunction,
	FString& OutKind,
	bool& bOutUnsupportedClass)
{
	bOutUnsupportedClass = false;
	OutKind.Reset();
	if (!Node || !IsValid(Node))
	{
		return false;
	}
	if (const UK2Node_CallFunction* const Call = Cast<UK2Node_CallFunction>(Node))
	{
		if (Call->FunctionReference.GetMemberName().ToString() != FromFunction
			|| !IsSameClass(Call->FunctionReference.GetMemberParentClass(Call->GetBlueprintClassFromNode()), FromOwner))
		{
			return false;
		}
		// `UK2Node_Message` derives from `UK2Node_CallFunction`, so the message test comes first and no node is reported twice.
		if (Call->IsA<UK2Node_Message>())
		{
			OutKind = KindMessage;
			bOutUnsupportedClass = Node->GetClass() != UK2Node_Message::StaticClass();
		}
		else
		{
			OutKind = KindTypedCall;
			bOutUnsupportedClass = Node->GetClass() != UK2Node_CallFunction::StaticClass();
		}
		return true;
	}
	if (const UK2Node_DynamicCast* const CastNode = Cast<UK2Node_DynamicCast>(Node))
	{
		if (!IsSameClass(CastNode->TargetType, FromOwner))
		{
			return false;
		}
		OutKind = KindCast;
		bOutUnsupportedClass = Node->GetClass() != UK2Node_DynamicCast::StaticClass();
		return true;
	}
	return false;
}

int32 FCortexGraphRetargetOps::CountRemainingSites(UBlueprint* Blueprint, const UClass* FromOwner, const FString& FromFunction, FString& OutFirstSite)
{
	OutFirstSite.Reset();
	TArray<FCortexGraphPatchGraphRef> Graphs;
	FCortexGraphPatchOps::CollectAddressableGraphs(Blueprint, Graphs);
	int32 Count = 0;
	for (const FCortexGraphPatchGraphRef& Ref : Graphs)
	{
		if (!Ref.Graph) continue;
		for (const UEdGraphNode* Node : Ref.Graph->Nodes)
		{
			FString Kind;
			bool bUnsupported = false;
			if (ClassifySite(Node, FromOwner, FromFunction, Kind, bUnsupported))
			{
				if (Count == 0)
				{
					OutFirstSite = FString::Printf(TEXT("%s in graph '%s'"), *NodeLabel(*Node), *Ref.Graph->GetName());
				}
				++Count;
			}
		}
	}
	return Count;
}

bool FCortexGraphRetargetOps::ResolveEndpoints(
	const FCortexGraphMigrationRetargetPlan& Plan,
	UClass*& OutFromOwner,
	UClass*& OutToOwner,
	UFunction*& OutToFunction,
	FCortexCommandResult& OutError)
{
	OutFromOwner = nullptr;
	OutToOwner = nullptr;
	OutToFunction = nullptr;
	if (!FCortexGraphInterfaceMigration::ResolveClassIdentifier(Plan.FromOwner, OutFromOwner, OutError)
		|| !FCortexGraphInterfaceMigration::ResolveClassIdentifier(Plan.ToOwner, OutToOwner, OutError))
	{
		return false;
	}
	OutToFunction = OutToOwner->FindFunctionByName(FName(*Plan.ToFunction));
	if (!OutToFunction)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation,
			FString::Printf(TEXT("'%s' declares no function '%s'"), *Plan.ToOwner, *Plan.ToFunction));
		return false;
	}
	return true;
}

/** The literal of one reviewed input pin and the replacement pin it has to reach. */
struct FCortexGraphRetargetDefault
{
	FString NewPin;
	FString TypeSignature;
	FString Value;
	TWeakObjectPtr<UObject> Object;
	FText Text;
};

/** Captures the user-authored literals of the unlinked, mapped input pins of one node before it is reconstructed. */
static TArray<FCortexGraphRetargetDefault> CaptureDefaults(const UEdGraphNode& Node, const FCortexGraphRetargetSite& Site)
{
	TArray<FCortexGraphRetargetDefault> Captured;
	for (const UEdGraphPin* Pin : Node.Pins)
	{
		if (!Pin || Pin->ParentPin != nullptr || !HasUserDefault(*Pin)) continue;
		const FCortexGraphRetargetPin* Reviewed = FindPin(Site, Pin->PinName.ToString(), static_cast<int32>(Pin->Direction));
		if (!Reviewed || Reviewed->MapsTo.IsEmpty() || !Reviewed->Links.IsEmpty()) continue;
		FCortexGraphRetargetDefault Default;
		Default.NewPin = Reviewed->MapsTo;
		Default.TypeSignature = PinTypeSignature(*Pin);
		Default.Value = Pin->DefaultValue;
		Default.Object = Pin->DefaultObject;
		Default.Text = Pin->DefaultTextValue;
		Captured.Add(MoveTemp(Default));
	}
	return Captured;
}

/** Writes the captured literals onto the final node when the replacement pin carries the same type and not the same literal yet. */
static void ApplyDefaults(UEdGraphNode& Node, const TArray<FCortexGraphRetargetDefault>& Captured)
{
	const UEdGraphSchema_K2* const Schema = GetDefault<UEdGraphSchema_K2>();
	for (const FCortexGraphRetargetDefault& Default : Captured)
	{
		UEdGraphPin* const Pin = Node.FindPin(FName(*Default.NewPin), EGPD_Input);
		if (!Pin || !Pin->LinkedTo.IsEmpty() || PinTypeSignature(*Pin) != Default.TypeSignature) continue;
		if (Default.Object.IsValid())
		{
			if (Pin->DefaultObject != Default.Object.Get()) Schema->TrySetDefaultObject(*Pin, Default.Object.Get());
		}
		else if (!Default.Text.IsEmpty())
		{
			if (!Pin->DefaultTextValue.EqualTo(Default.Text)) Schema->TrySetDefaultText(*Pin, Default.Text);
		}
		else if (Pin->DefaultValue != Default.Value)
		{
			Schema->TrySetDefaultValue(*Pin, Default.Value);
		}
	}
}

bool FCortexGraphRetargetOps::ApplyNodeRetarget(
	UEdGraphNode* Node,
	const FCortexGraphRetargetSite& Site,
	UClass* ToOwner,
	const FString& ToFunction,
	FString& OutFailure)
{
	if (!Node)
	{
		OutFailure = FString::Printf(TEXT("site node %s is missing"), *Site.NodeGuid);
		return false;
	}
	Node->Modify();
	const TArray<FCortexGraphRetargetDefault> Defaults = CaptureDefaults(*Node, Site);
	const bool bPreviousOrphanSaving = Node->bDisableOrphanPinSaving;
	Node->bDisableOrphanPinSaving = true;
	bool bApplied = false;
	if (Site.Kind == KindCast)
	{
		if (UK2Node_DynamicCast* const CastNode = Cast<UK2Node_DynamicCast>(Node))
		{
			CastNode->TargetType = ToOwner;
			bApplied = true;
		}
	}
	else if (UK2Node_CallFunction* const Call = Cast<UK2Node_CallFunction>(Node))
	{
		Call->FunctionReference.SetExternalMember(FName(*ToFunction), ToOwner);
		bApplied = true;
	}
	if (bApplied)
	{
		Node->ReconstructNode();
		ApplyDefaults(*Node, Defaults);
	}
	Node->bDisableOrphanPinSaving = bPreviousOrphanSaving;
	if (!bApplied)
	{
		OutFailure = FString::Printf(TEXT("site node %s is not a %s node"), *Site.NodeGuid, *Site.Kind);
	}
	return bApplied;
}

UK2Node_CallFunction* FCortexGraphRetargetOps::CreateCallReplacement(
	UEdGraph* Graph,
	const UEdGraphNode* Old,
	const FCortexGraphRetargetSite& Site,
	const FGuid& ReplacementGuid,
	UClass* ToOwner,
	const FString& ToFunction,
	FString& OutFailure)
{
	if (!Graph || !Old || !ReplacementGuid.IsValid())
	{
		OutFailure = TEXT("the replacement call needs a graph, the replaced node and a planned identity");
		return nullptr;
	}
	Graph->Modify();
	UK2Node_CallFunction* const Call = NewObject<UK2Node_CallFunction>(Graph, NAME_None, RF_Transactional);
	Call->FunctionReference.SetExternalMember(FName(*ToFunction), ToOwner);
	Call->NodeGuid = ReplacementGuid;
	Call->NodePosX = Old->NodePosX;
	Call->NodePosY = Old->NodePosY;
	Call->NodeComment = Old->NodeComment;
	Call->bCommentBubblePinned = Old->bCommentBubblePinned;
	Call->bCommentBubbleVisible = Old->bCommentBubbleVisible;
	Call->SetEnabledState(Old->GetDesiredEnabledState(), Old->HasUserSetTheEnabledState());
	Call->SetForceDisplayAsDisabled(Old->IsDisplayAsDisabledForced());
	Graph->AddNode(Call, false, false);
	Call->AllocateDefaultPins();
	ApplyDefaults(*Call, CaptureDefaults(*Old, Site));
	return Call;
}

bool FCortexGraphRetargetOps::PlanRetarget(
	UBlueprint* Blueprint,
	const TSharedPtr<FJsonObject>& Migration,
	const FString& PatchId,
	FCortexGraphMigrationRetargetPlan& OutPlan,
	FCortexCommandResult& OutError)
{
	OutPlan = FCortexGraphMigrationRetargetPlan();
	OutError = FCortexCommandResult();
	if (!Blueprint)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::BlueprintNotFound, TEXT("Blueprint is null"));
		return false;
	}
	if (!Migration.IsValid())
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("migration must be an object"));
		return false;
	}
	if (!FCortexGraphPatchOps::HasOnlyFields(Migration,
		{ TEXT("op"), TEXT("from"), TEXT("to"), TEXT("pin_map"), TEXT("sites") }, OutError, TEXT("migration")))
	{
		return false;
	}
	FString Op;
	if (!FCortexGraphPatchOps::ReadRequiredString(Migration, TEXT("op"), Op, OutError)) return false;
	if (Op != RetargetOpName)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::UnsupportedOperation, TEXT("migration.op must be retarget_calls"));
		return false;
	}

	const TSharedPtr<FJsonObject>* FromPtr = nullptr;
	const TSharedPtr<FJsonObject>* ToPtr = nullptr;
	if (!Migration->TryGetObjectField(TEXT("from"), FromPtr) || !FromPtr || !FromPtr->IsValid()
		|| !Migration->TryGetObjectField(TEXT("to"), ToPtr) || !ToPtr || !ToPtr->IsValid())
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
			TEXT("migration.from and migration.to must be objects with owner and function"));
		return false;
	}
	if (!FCortexGraphPatchOps::HasOnlyFields(*FromPtr, { TEXT("owner"), TEXT("function") }, OutError, TEXT("migration.from"))
		|| !FCortexGraphPatchOps::HasOnlyFields(*ToPtr, { TEXT("owner"), TEXT("function"), TEXT("mode") }, OutError, TEXT("migration.to"))
		|| !FCortexGraphPatchOps::ReadRequiredString(*FromPtr, TEXT("owner"), OutPlan.FromOwner, OutError)
		|| !FCortexGraphPatchOps::ReadRequiredString(*FromPtr, TEXT("function"), OutPlan.FromFunction, OutError)
		|| !FCortexGraphPatchOps::ReadRequiredString(*ToPtr, TEXT("owner"), OutPlan.ToOwner, OutError)
		|| !FCortexGraphPatchOps::ReadRequiredString(*ToPtr, TEXT("function"), OutPlan.ToFunction, OutError))
	{
		return false;
	}

	UClass* FromOwner = nullptr;
	UClass* ToOwner = nullptr;
	{
		FCortexCommandResult ResolveError;
		if (!FCortexGraphInterfaceMigration::ResolveClassIdentifier(OutPlan.FromOwner, FromOwner, ResolveError))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, FString::Printf(TEXT("migration.from.owner: %s"), *ResolveError.ErrorMessage));
			return false;
		}
		if (!FCortexGraphInterfaceMigration::ResolveClassIdentifier(OutPlan.ToOwner, ToOwner, ResolveError))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, FString::Printf(TEXT("migration.to.owner: %s"), *ResolveError.ErrorMessage));
			return false;
		}
	}
	OutPlan.Op = RetargetOpName;
	OutPlan.FromOwner = ClassPathOf(FromOwner);
	OutPlan.ToOwner = ClassPathOf(ToOwner);
	UFunction* const ToFunction = ToOwner->FindFunctionByName(FName(*OutPlan.ToFunction));
	if (!ToFunction || !UEdGraphSchema_K2::CanUserKismetCallFunction(ToFunction))
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
			FString::Printf(TEXT("migration.to: '%s' declares no Blueprint-callable function '%s'"), *OutPlan.ToOwner, *OutPlan.ToFunction));
		return false;
	}
	if (IsSameClass(FromOwner, ToOwner) && OutPlan.FromFunction == OutPlan.ToFunction)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("migration.from and migration.to name the same function"));
		return false;
	}
	OutPlan.Mode = ToOwner->HasAnyClassFlags(CLASS_Interface) ? ModeMessage : ModeCall;
	if ((*ToPtr)->HasField(TEXT("mode")))
	{
		FString Mode;
		if (!(*ToPtr)->TryGetStringField(TEXT("mode"), Mode) || (Mode != ModeMessage && Mode != ModeCall))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("migration.to.mode must be 'message' or 'call'"));
			return false;
		}
		OutPlan.Mode = Mode;
	}
	if (OutPlan.Mode == ModeMessage && !ToOwner->HasAnyClassFlags(CLASS_Interface))
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
			FString::Printf(TEXT("migration.to.mode 'message' needs an interface owner; '%s' is not an interface"), *OutPlan.ToOwner));
		return false;
	}

	if (Migration->HasField(TEXT("pin_map")))
	{
		const TArray<TSharedPtr<FJsonValue>>* MapValues = nullptr;
		if (!Migration->TryGetArrayField(TEXT("pin_map"), MapValues) || !MapValues)
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("migration.pin_map must be an array"));
			return false;
		}
		TSet<FString> SeenFrom;
		TSet<FString> SeenTo;
		for (const TSharedPtr<FJsonValue>& Value : *MapValues)
		{
			const TSharedPtr<FJsonObject> EntryJson = Value.IsValid() ? Value->AsObject() : nullptr;
			FCortexGraphRetargetPinMapping Entry;
			if (!EntryJson.IsValid()
				|| !FCortexGraphPatchOps::HasOnlyFields(EntryJson, { TEXT("from_pin"), TEXT("to_pin") }, OutError, TEXT("migration.pin_map entry"))
				|| !FCortexGraphPatchOps::ReadRequiredString(EntryJson, TEXT("from_pin"), Entry.FromPin, OutError)
				|| !FCortexGraphPatchOps::ReadRequiredString(EntryJson, TEXT("to_pin"), Entry.ToPin, OutError))
			{
				if (OutError.ErrorCode.IsEmpty())
				{
					OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("every migration.pin_map entry must be an object with from_pin and to_pin"));
				}
				return false;
			}
			if (SeenFrom.Contains(Entry.FromPin) || SeenTo.Contains(Entry.ToPin))
			{
				OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
					FString::Printf(TEXT("migration.pin_map names the pin '%s' -> '%s' twice"), *Entry.FromPin, *Entry.ToPin));
				return false;
			}
			SeenFrom.Add(Entry.FromPin);
			SeenTo.Add(Entry.ToPin);
			OutPlan.PinMap.Add(MoveTemp(Entry));
		}
	}

	// The caller's echo, parsed strictly: it is compared with the discovered set, never substituted for it.
	bool bHasEcho = false;
	TArray<FCortexGraphRetargetSite> Echo;
	if (Migration->HasField(TEXT("sites")))
	{
		const TArray<TSharedPtr<FJsonValue>>* SiteValues = nullptr;
		if (!Migration->TryGetArrayField(TEXT("sites"), SiteValues) || !SiteValues)
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField, TEXT("migration.sites must be an array"));
			return false;
		}
		bHasEcho = true;
		TSet<FString> Seen;
		for (const TSharedPtr<FJsonValue>& Value : *SiteValues)
		{
			FCortexGraphRetargetSite Site;
			if (!FCortexGraphRetargetSite::FromJson(Value.IsValid() ? Value->AsObject() : nullptr, Site, OutError))
			{
				return false;
			}
			if (Seen.Contains(Site.NodeGuid))
			{
				OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
					FString::Printf(TEXT("migration.sites repeats the site '%s'"), *Site.NodeGuid));
				return false;
			}
			Seen.Add(Site.NodeGuid);
			Echo.Add(MoveTemp(Site));
		}
	}

	// Discovery: every message, typed call and cast of the old owner in every graph of the asset, matched by resolved owner.
	TArray<FCortexGraphPatchGraphRef> GraphRefs;
	FCortexGraphPatchOps::CollectAddressableGraphs(Blueprint, GraphRefs);
	struct FFound
	{
		UEdGraphNode* Node = nullptr;
		const FCortexGraphPatchGraphRef* Ref = nullptr;
		bool bUnsupportedClass = false;
		FCortexGraphRetargetSite Site;
	};
	TArray<FFound> Found;
	for (const FCortexGraphPatchGraphRef& Ref : GraphRefs)
	{
		if (!Ref.Graph) continue;
		OutPlan.ScannedNodes += Ref.Graph->Nodes.Num();
		for (UEdGraphNode* Node : Ref.Graph->Nodes)
		{
			FString Kind;
			bool bUnsupported = false;
			if (!ClassifySite(Node, FromOwner, OutPlan.FromFunction, Kind, bUnsupported))
			{
				continue;
			}
			if (Found.Num() >= MaxSites)
			{
				OutError = FCortexCommandRouter::Error(CortexErrorCodes::LimitExceeded,
					FString::Printf(TEXT("retarget_calls found more than %d sites in this asset; the request is refused instead of approving an incomplete set"), MaxSites));
				return false;
			}
			FFound Entry;
			Entry.Node = Node;
			Entry.Ref = &Ref;
			Entry.bUnsupportedClass = bUnsupported;
			Entry.Site.GraphGuid = Ref.Graph->GraphGuid.ToString();
			Entry.Site.SubgraphPath = Ref.SubgraphPath;
			Entry.Site.NodeGuid = NodeGuidText(*Node);
			Entry.Site.NodeClassPath = Node->GetClass()->GetPathName();
			Entry.Site.Kind = Kind;
			Found.Add(MoveTemp(Entry));
		}
	}
	if (Found.IsEmpty())
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation,
			FString::Printf(TEXT("this asset has no message, typed call or cast of '%s.%s' to retarget"), *OutPlan.FromOwner, *OutPlan.FromFunction));
		return false;
	}
	Found.Sort([](const FFound& A, const FFound& B)
	{
		return A.Site.GraphGuid != B.Site.GraphGuid ? A.Site.GraphGuid < B.Site.GraphGuid : A.Site.NodeGuid < B.Site.NodeGuid;
	});

	// The replacement model of every site.
	FRetargetModel Model;
	BuildModel(Blueprint, Model);
	TMap<FString, UEdGraphNode*> ModelByGuid;
	for (FFound& Entry : Found)
	{
		if (Entry.bUnsupportedClass)
		{
			continue;
		}
		ModelByGuid.Add(Entry.Site.NodeGuid, BuildModelNode(Model, *Entry.Node, Entry.Site.Kind, OutPlan.Mode, ToOwner, OutPlan.ToFunction));
	}
	TMap<FString, const FFound*> FoundByGuid;
	for (const FFound& Entry : Found)
	{
		FoundByGuid.Add(Entry.Site.NodeGuid, &Entry);
	}
	const UEdGraphSchema_K2* const Schema = GetDefault<UEdGraphSchema_K2>();

	TSet<FString> UsedFromPins;
	TSet<FString> UsedToPins;
	// Pass 1 inventories every site (pins, links, replacement pins) so that pass 2 can compare links between two sites.
	TMap<FString, TSet<FString>> ReasonsByGuid;
	for (FFound& Entry : Found)
	{
		FCortexGraphRetargetSite& Site = Entry.Site;
		TSet<FString>& Reasons = ReasonsByGuid.FindOrAdd(Site.NodeGuid);
		UEdGraphNode* const ModelNode = ModelByGuid.FindRef(Site.NodeGuid);
		if (!Entry.Ref->bMutable)
		{
			Reasons.Add(FString::Printf(TEXT("graph_not_mutable: the %s graph '%s' is not mutable"), *Entry.Ref->Kind, *Entry.Ref->Graph->GetName()));
		}
		if (Entry.bUnsupportedClass)
		{
			Reasons.Add(FString::Printf(TEXT("unsupported_node_class: %s is a subclass this operation does not rewrite"), *Entry.Node->GetClass()->GetName()));
		}
		if (Site.Kind == KindMessage && OutPlan.Mode == ModeCall)
		{
			Site.ReplacementGuid = FCortexGraphPatchOps::DeriveNodeGuid(PatchId, FString(TEXT("retarget:")) + Site.NodeGuid).ToString();
		}

		for (UEdGraphPin* Pin : Entry.Node->Pins)
		{
			if (!Pin) continue;
			if (Pin->ParentPin != nullptr) continue;
			FCortexGraphRetargetPin Reviewed;
			Reviewed.Name = Pin->PinName.ToString();
			Reviewed.Direction = static_cast<int32>(Pin->Direction);
			Reviewed.Signature = PinSignature(*Pin);
			if (Pin->SubPins.Num() > 0)
			{
				Reasons.Add(FString::Printf(TEXT("split_pin: the pin '%s' is split, which this operation does not retarget"), *Reviewed.Name));
			}
			for (const UEdGraphPin* Linked : Pin->LinkedTo)
			{
				const UEdGraphNode* const FarNode = Linked ? Linked->GetOwningNode() : nullptr;
				if (!FarNode) continue;
				Reviewed.Links.Add({ NodeGuidText(*FarNode), Linked->PinName.ToString() });
			}
			Reviewed.Links.Sort(LinkLess);
			if (ModelNode)
			{
				Reviewed.MapsTo = CounterpartName(OutPlan, Site.Kind, *Pin, *ModelNode, FromOwner);
			}
			Site.Pins.Add(MoveTemp(Reviewed));
		}
		Site.Pins.Sort(PinLess);
	}
	for (FFound& Entry : Found)
	{
		FCortexGraphRetargetSite& Site = Entry.Site;
		TSet<FString>& Reasons = ReasonsByGuid.FindOrAdd(Site.NodeGuid);
		UEdGraphNode* const ModelNode = ModelByGuid.FindRef(Site.NodeGuid);

		// Which pin_map entries the asset actually exercises.
		for (const FCortexGraphRetargetPin& Reviewed : Site.Pins)
		{
			for (const FCortexGraphRetargetPinMapping& Entry2 : OutPlan.PinMap)
			{
				if (Entry2.FromPin == Reviewed.Name && Site.Kind != KindCast)
				{
					UsedFromPins.Add(Entry2.FromPin);
				}
				if (ModelNode && Entry2.ToPin == Reviewed.MapsTo && Entry2.FromPin == Reviewed.Name && Site.Kind != KindCast)
				{
					UsedToPins.Add(Entry2.ToPin);
				}
			}
		}

		if (ModelNode)
		{
			TSet<FString> Counterparts;
			for (UEdGraphPin* Pin : Entry.Node->Pins)
			{
				if (!Pin || Pin->ParentPin != nullptr) continue;
				const FCortexGraphRetargetPin* Reviewed = FindPin(Site, Pin->PinName.ToString(), static_cast<int32>(Pin->Direction));
				if (!Reviewed) continue;
				if (Reviewed->MapsTo.IsEmpty())
				{
					if (!Reviewed->Links.IsEmpty())
					{
						Reasons.Add(FString::Printf(TEXT("pin_unmapped: the linked pin '%s' has no counterpart on the replacement; add a pin_map entry"), *Reviewed->Name));
					}
					else if (HasUserDefault(*Pin))
					{
						Reasons.Add(FString::Printf(TEXT("default_lost: the pin '%s' carries a literal and has no counterpart on the replacement"), *Reviewed->Name));
					}
					continue;
				}
				const FString CounterpartKey = FString::Printf(TEXT("%s|%d"), *Reviewed->MapsTo, Reviewed->Direction);
				if (Counterparts.Contains(CounterpartKey))
				{
					Reasons.Add(FString::Printf(TEXT("pin_collision: two pins map onto the replacement pin '%s'"), *Reviewed->MapsTo));
				}
				Counterparts.Add(CounterpartKey);

				UEdGraphPin* const NewPin = ModelNode->FindPin(FName(*Reviewed->MapsTo), Pin->Direction);
				if (Reviewed->Links.IsEmpty())
				{
					if (HasUserDefault(*Pin) && NewPin && PinTypeSignature(*Pin) != PinTypeSignature(*NewPin))
					{
						Reasons.Add(FString::Printf(TEXT("default_lost: the literal of the pin '%s' cannot carry across the type change to '%s'"), *Reviewed->Name, *Reviewed->MapsTo));
					}
					continue;
				}
				for (const UEdGraphPin* Linked : Pin->LinkedTo)
				{
					const UEdGraphNode* const FarNode = Linked ? Linked->GetOwningNode() : nullptr;
					if (!FarNode || !NewPin) continue;
					// A far endpoint that is itself a site is compared through its own replacement pin.
					UEdGraphPin* FarCheck = const_cast<UEdGraphPin*>(Linked);
					if (const FFound* const* FarFound = FoundByGuid.Find(NodeGuidText(*FarNode)))
					{
						const FCortexGraphRetargetPin* FarReviewed = FindPin((*FarFound)->Site, Linked->PinName.ToString(), static_cast<int32>(Linked->Direction));
						UEdGraphNode* const FarModel = ModelByGuid.FindRef(NodeGuidText(*FarNode));
						if (FarReviewed && !FarReviewed->MapsTo.IsEmpty() && FarModel)
						{
							FarCheck = FarModel->FindPin(FName(*FarReviewed->MapsTo), Linked->Direction);
						}
					}
					if (!FarCheck) continue;
					const FPinConnectionResponse Response = Schema->CanCreateConnection(FarCheck, NewPin);
					bool bAcceptable = Response.Response == CONNECT_RESPONSE_MAKE;
					if (!bAcceptable
						&& (Response.Response == CONNECT_RESPONSE_BREAK_OTHERS_A || Response.Response == CONNECT_RESPONSE_BREAK_OTHERS_B
							|| Response.Response == CONNECT_RESPONSE_BREAK_OTHERS_AB))
					{
						// The displaced links are acceptable only when every one of them is a link of a site this apply re-makes.
						bAcceptable = true;
						for (const UEdGraphPin* Displaced : FarCheck->LinkedTo)
						{
							const UEdGraphNode* const DisplacedOwner = Displaced ? Displaced->GetOwningNode() : nullptr;
							if (!DisplacedOwner || !FoundByGuid.Contains(NodeGuidText(*DisplacedOwner)))
							{
								bAcceptable = false;
							}
						}
					}
					if (!bAcceptable)
					{
						if (Schema->IsSelfPin(*Pin))
						{
							Reasons.Add(FString::Printf(TEXT("target_incompatible: the target link %s.%s cannot connect to the replacement's target pin: %s"),
								*NodeGuidText(*FarNode), *Linked->PinName.ToString(), *Response.Message.ToString()));
						}
						else
						{
							Reasons.Add(FString::Printf(TEXT("link_incompatible: %s -> %s.%s cannot connect to the replacement pin '%s': %s"),
								*Reviewed->Name, *NodeGuidText(*FarNode), *Linked->PinName.ToString(), *Reviewed->MapsTo, *Response.Message.ToString()));
						}
					}
				}
			}
		}
		TArray<FString> Sorted = Reasons.Array();
		Sorted.Sort();
		Site.Blocked = FString::Join(Sorted, TEXT("; "));
	}

	for (const FCortexGraphRetargetPinMapping& Entry : OutPlan.PinMap)
	{
		if (!UsedFromPins.Contains(Entry.FromPin))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
				FString::Printf(TEXT("migration.pin_map names the pin '%s', which no site of '%s.%s' carries"), *Entry.FromPin, *OutPlan.FromOwner, *OutPlan.FromFunction));
			return false;
		}
		if (!UsedToPins.Contains(Entry.ToPin))
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidField,
				FString::Printf(TEXT("migration.pin_map maps '%s' to '%s', which is not a pin of the replacement for any site"), *Entry.FromPin, *Entry.ToPin));
			return false;
		}
	}

	for (FFound& Entry : Found)
	{
		OutPlan.Sites.Add(Entry.Site);
	}

	// The exact echo: a missing, an extra and a re-linked site are all refused before anything can mutate.
	OutPlan.bAwaitingApproval = !bHasEcho;
	if (bHasEcho)
	{
		TMap<FString, FString> Discovered;
		for (const FCortexGraphRetargetSite& Site : OutPlan.Sites)
		{
			Discovered.Add(Site.NodeGuid, Site.Key());
		}
		TMap<FString, FString> Reviewed;
		for (const FCortexGraphRetargetSite& Site : Echo)
		{
			Reviewed.Add(Site.NodeGuid, Site.Key());
		}
		TArray<FString> Missing;
		TArray<FString> Extra;
		TArray<FString> Changed;
		for (const TPair<FString, FString>& Pair : Discovered)
		{
			const FString* Echoed = Reviewed.Find(Pair.Key);
			if (!Echoed) Missing.Add(Pair.Key);
			else if (*Echoed != Pair.Value) Changed.Add(Pair.Key);
		}
		for (const TPair<FString, FString>& Pair : Reviewed)
		{
			if (!Discovered.Contains(Pair.Key)) Extra.Add(Pair.Key);
		}
		if (!Missing.IsEmpty() || !Extra.IsEmpty() || !Changed.IsEmpty())
		{
			Missing.Sort();
			Extra.Sort();
			Changed.Sort();
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation,
				FString::Printf(TEXT("migration.sites must exactly equal the site set of '%s.%s' the preview published (missing: %s; extra: %s; re-linked or changed: %s)"),
					*OutPlan.FromOwner, *OutPlan.FromFunction,
					Missing.IsEmpty() ? TEXT("none") : *FString::Join(Missing, TEXT(", ")),
					Extra.IsEmpty() ? TEXT("none") : *FString::Join(Extra, TEXT(", ")),
					Changed.IsEmpty() ? TEXT("none") : *FString::Join(Changed, TEXT(", "))));
			return false;
		}
	}

	// The preservation contract and the expected node set of every graph that owns a site.
	TArray<FString> GraphOrder;
	for (const FCortexGraphRetargetSite& Site : OutPlan.Sites)
	{
		GraphOrder.AddUnique(Site.GraphGuid);
	}
	for (const FString& GraphGuidText : GraphOrder)
	{
		const FFound* FirstInGraph = nullptr;
		for (const FFound& Entry : Found)
		{
			if (Entry.Site.GraphGuid == GraphGuidText) { FirstInGraph = &Entry; break; }
		}
		UEdGraph* const Graph = FirstInGraph ? FirstInGraph->Ref->Graph : nullptr;
		if (!Graph) continue;

		TArray<FGuid> Excluded;
		TArray<FString> ExcludedText;
		TSet<FString> NodeGuids;
		for (const UEdGraphNode* Node : Graph->Nodes)
		{
			if (IsValid(Node)) NodeGuids.Add(NodeGuidText(*Node));
		}
		const int32 NodeCount = NodeGuids.Num();
		for (const FCortexGraphRetargetSite& Site : OutPlan.Sites)
		{
			if (Site.GraphGuid != GraphGuidText) continue;
			FGuid Old;
			FGuid::Parse(Site.NodeGuid, Old);
			Excluded.Add(Old);
			ExcludedText.Add(Site.NodeGuid);
			if (!Site.ReplacementGuid.IsEmpty())
			{
				FGuid Replacement;
				FGuid::Parse(Site.ReplacementGuid, Replacement);
				Excluded.Add(Replacement);
				ExcludedText.Add(Site.ReplacementGuid);
				NodeGuids.Remove(Site.NodeGuid);
				NodeGuids.Add(Site.ReplacementGuid);
			}
		}
		FCortexGraphRetargetGraph GraphPlan;
		GraphPlan.GraphGuid = GraphGuidText;
		GraphPlan.SubgraphPath = FirstInGraph->Ref->SubgraphPath;
		GraphPlan.NodeCount = NodeCount;
		GraphPlan.ExpectedNodeDigest = NodeSetDigest(NodeGuids.Array());
		OutPlan.Graphs.Add(MoveTemp(GraphPlan));

		FCortexGraphTransferPreservation Preservation;
		Preservation.Label = FString::Printf(TEXT("retarget_calls:%s"), *Graph->GetName());
		Preservation.GraphGuid = GraphGuidText;
		Preservation.ExcludedGuids = ExcludedText;
		Preservation.Capture = FCortexGraphMigrationOps::CapturePreservation(Blueprint, Graph, Excluded);
		if (Preservation.Capture.IsEmpty())
		{
			OutError = FCortexCommandRouter::Error(CortexErrorCodes::InvalidOperation, TEXT("retarget_calls preservation could not be captured"));
			return false;
		}
		OutPlan.Preservations.Add(MoveTemp(Preservation));
	}

	// The preview is the approval contract: a complete inventory is published only when the bridge can carry it whole.
	const TSharedPtr<FJsonObject> Inventory = MakeInventory(OutPlan);
	int32 InventoryChars = 0;
	const bool bMeasured = Inventory.IsValid() && FCortexGraphMigrationOps::EncodedResponseChars(Inventory, InventoryChars);
	if (!bMeasured || InventoryChars > FCortexGraphMigrationOps::MaxPublishableCallOutputInventoryChars)
	{
		OutError = FCortexCommandRouter::Error(CortexErrorCodes::LimitExceeded,
			FString::Printf(TEXT("the complete retarget_calls inventory of '%s.%s' with %d site(s) %s, which is above the publishable %d; the request is refused without changing the asset instead of approving an inventory the caller cannot review in full"),
				*OutPlan.FromOwner, *OutPlan.FromFunction, OutPlan.Sites.Num(),
				bMeasured ? *FString::Printf(TEXT("encodes to %d character(s)"), InventoryChars) : TEXT("could not be encoded"),
				FCortexGraphMigrationOps::MaxPublishableCallOutputInventoryChars));
		OutError.ErrorDetails = MakeShared<FJsonObject>();
		OutError.ErrorDetails->SetNumberField(TEXT("response_char_limit"), FCortexGraphMigrationOps::BridgeResponseCharLimit);
		OutError.ErrorDetails->SetNumberField(TEXT("inventory_chars"), InventoryChars);
		OutError.ErrorDetails->SetNumberField(TEXT("sites"), OutPlan.Sites.Num());
		OutError.ErrorDetails->SetBoolField(TEXT("complete"), false);
		return false;
	}
	return true;
}

bool FCortexGraphRetargetOps::VerifyRetargetAgainstNative(
	UBlueprint* Blueprint,
	const FCortexGraphMigrationRetargetPlan& Plan,
	TFunctionRef<bool(const TCHAR*)> FaultProbe,
	FString& OutFailure)
{
	UClass* FromOwner = nullptr;
	UClass* ToOwner = nullptr;
	UFunction* ToFunction = nullptr;
	FCortexCommandResult ResolveError;
	if (!ResolveEndpoints(Plan, FromOwner, ToOwner, ToFunction, ResolveError))
	{
		OutFailure = ResolveError.ErrorMessage;
		return false;
	}

	// 1. The exact node set of every touched graph.
	for (const FCortexGraphRetargetGraph& GraphPlan : Plan.Graphs)
	{
		FGuid GraphGuid;
		FGuid::Parse(GraphPlan.GraphGuid, GraphGuid);
		UEdGraph* const Graph = FCortexGraphMigrationOps::FindGraphByGuid(Blueprint, GraphGuid);
		if (!Graph)
		{
			OutFailure = FString::Printf(TEXT("the retargeted graph %s did not re-resolve"), *GraphPlan.GraphGuid);
			return false;
		}
		TArray<FString> Guids;
		for (const UEdGraphNode* Node : Graph->Nodes)
		{
			if (IsValid(Node)) Guids.Add(NodeGuidText(*Node));
		}
		if (NodeSetDigest(Guids) != GraphPlan.ExpectedNodeDigest)
		{
			OutFailure = FString::Printf(TEXT("the node set of graph '%s' is not the expected one: %d node(s) now, the plan expects the reviewed nodes minus the replaced messages plus their replacements"),
				*Graph->GetName(), Guids.Num());
			return false;
		}
	}
	if (FaultProbe(TEXT("retarget_nodes")))
	{
		OutFailure = TEXT("retarget_calls readback divergence injected after the node-set comparison");
		return false;
	}

	// 2. Every site: the node, its reference and its links by (node GUID, pin name).
	for (const FCortexGraphRetargetSite& Site : Plan.Sites)
	{
		FGuid GraphGuid;
		FGuid::Parse(Site.GraphGuid, GraphGuid);
		UEdGraph* const Graph = FCortexGraphMigrationOps::FindGraphByGuid(Blueprint, GraphGuid);
		FGuid AfterGuid;
		FGuid::Parse(SiteNodeAfter(Site), AfterGuid);
		UEdGraphNode* const Node = FCortexGraphMigrationOps::FindNodeByGuidInGraph(Graph, AfterGuid);
		if (!Node)
		{
			OutFailure = FString::Printf(TEXT("the site node %s did not re-resolve after the apply"), *SiteNodeAfter(Site));
			return false;
		}
		if (!Site.ReplacementGuid.IsEmpty())
		{
			FGuid OldGuid;
			FGuid::Parse(Site.NodeGuid, OldGuid);
			if (FCortexGraphMigrationOps::FindNodeByGuidInGraph(Graph, OldGuid))
			{
				OutFailure = FString::Printf(TEXT("the replaced message node %s is still in its graph"), *Site.NodeGuid);
				return false;
			}
			if (Node->GetClass() != UK2Node_CallFunction::StaticClass())
			{
				OutFailure = FString::Printf(TEXT("the replacement %s is a %s, not a direct typed call"), *Site.ReplacementGuid, *Node->GetClass()->GetName());
				return false;
			}
		}
		else if (Node->GetClass()->GetPathName() != Site.NodeClassPath)
		{
			OutFailure = FString::Printf(TEXT("the site node %s changed class to %s"), *Site.NodeGuid, *Node->GetClass()->GetName());
			return false;
		}
		if (const UK2Node_CallFunction* const Call = Cast<UK2Node_CallFunction>(Node))
		{
			if (Call->FunctionReference.GetMemberName().ToString() != Plan.ToFunction
				|| !IsSameClass(Call->FunctionReference.GetMemberParentClass(Call->GetBlueprintClassFromNode()), ToOwner))
			{
				OutFailure = FString::Printf(TEXT("the function reference of %s is not %s.%s"), *SiteNodeAfter(Site), *Plan.ToOwner, *Plan.ToFunction);
				return false;
			}
			if (!Call->GetTargetFunction())
			{
				OutFailure = FString::Printf(TEXT("the function reference of %s does not resolve to a function"), *SiteNodeAfter(Site));
				return false;
			}
		}
		else if (const UK2Node_DynamicCast* const CastNode = Cast<UK2Node_DynamicCast>(Node))
		{
			if (!IsSameClass(CastNode->TargetType, ToOwner))
			{
				OutFailure = FString::Printf(TEXT("the cast %s does not target %s"), *SiteNodeAfter(Site), *Plan.ToOwner);
				return false;
			}
		}
		else
		{
			OutFailure = FString::Printf(TEXT("the site node %s is neither a call nor a cast"), *SiteNodeAfter(Site));
			return false;
		}

		TMap<FString, TSet<FString>> ExpectedByPin;
		for (const FCortexGraphRetargetPin& Pin : Site.Pins)
		{
			if (Pin.Links.IsEmpty()) continue;
			if (Pin.MapsTo.IsEmpty())
			{
				OutFailure = FString::Printf(TEXT("the reviewed pin '%s' of %s is linked but has no replacement pin"), *Pin.Name, *Site.NodeGuid);
				return false;
			}
			TSet<FString>& Keys = ExpectedByPin.FindOrAdd(FString::Printf(TEXT("%s|dir=%d"), *Pin.MapsTo, Pin.Direction));
			if (!ExpectedLinks(Plan.Sites, Pin, Keys, OutFailure))
			{
				return false;
			}
		}
		for (const UEdGraphPin* Pin : Node->Pins)
		{
			if (!Pin || Pin->ParentPin != nullptr) continue;
			TSet<FString> Actual;
			for (const UEdGraphPin* Linked : Pin->LinkedTo)
			{
				const UEdGraphNode* const Far = Linked ? Linked->GetOwningNode() : nullptr;
				if (!Far) continue;
				Actual.Add(LinkKey(NodeGuidText(*Far), Linked->PinName.ToString(), static_cast<int32>(Linked->Direction)));
				if (!Linked->LinkedTo.Contains(Pin))
				{
					OutFailure = FString::Printf(TEXT("the link %s.%s -> %s.%s is not reciprocal"), *SiteNodeAfter(Site), *Pin->PinName.ToString(), *NodeGuidText(*Far), *Linked->PinName.ToString());
					return false;
				}
			}
			const TSet<FString>* Expected = ExpectedByPin.Find(FString::Printf(TEXT("%s|dir=%d"), *Pin->PinName.ToString(), static_cast<int32>(Pin->Direction)));
			const TSet<FString> Empty;
			if (!Actual.Difference(Expected ? *Expected : Empty).IsEmpty() || !(Expected ? *Expected : Empty).Difference(Actual).IsEmpty())
			{
				OutFailure = FString::Printf(TEXT("the links of pin '%s' on %s are not the reviewed ones: expected {%s}, found {%s}"),
					*Pin->PinName.ToString(), *SiteNodeAfter(Site),
					*FString::Join((Expected ? *Expected : Empty).Array(), TEXT(", ")), *FString::Join(Actual.Array(), TEXT(", ")));
				return false;
			}
		}
		for (const TPair<FString, TSet<FString>>& Pair : ExpectedByPin)
		{
			FString PinName;
			FString DirText;
			Pair.Key.Split(TEXT("|dir="), &PinName, &DirText);
			if (!Node->FindPin(FName(*PinName), static_cast<EEdGraphPinDirection>(FCString::Atoi(*DirText))))
			{
				OutFailure = FString::Printf(TEXT("the replacement pin '%s' of %s does not exist"), *PinName, *SiteNodeAfter(Site));
				return false;
			}
		}
	}
	if (FaultProbe(TEXT("retarget_links")))
	{
		OutFailure = TEXT("retarget_calls readback divergence injected after the link comparison");
		return false;
	}

	// 3. No site of the old endpoint remains.
	FString FirstRemaining;
	const int32 Remaining = CountRemainingSites(Blueprint, FromOwner, Plan.FromFunction, FirstRemaining);
	if (Remaining > 0)
	{
		OutFailure = FString::Printf(TEXT("%d site(s) of '%s.%s' remain, first: %s"), Remaining, *Plan.FromOwner, *Plan.FromFunction, *FirstRemaining);
		return false;
	}

	// 4. Everything outside the sites is exactly as captured.
	return FCortexGraphMigrationOps::VerifyPreservationContracts(Blueprint, Plan.Preservations, OutFailure);
}

TSharedPtr<FJsonObject> FCortexGraphRetargetOps::MakeInventory(const FCortexGraphMigrationRetargetPlan& Plan)
{
	TSharedPtr<FJsonObject> Inventory = MakeShared<FJsonObject>();
	Inventory->SetStringField(TEXT("operation"), Plan.Op);
	TSharedPtr<FJsonObject> From = MakeShared<FJsonObject>();
	From->SetStringField(TEXT("owner"), Plan.FromOwner);
	From->SetStringField(TEXT("function"), Plan.FromFunction);
	Inventory->SetObjectField(TEXT("from"), From);
	TSharedPtr<FJsonObject> To = MakeShared<FJsonObject>();
	To->SetStringField(TEXT("owner"), Plan.ToOwner);
	To->SetStringField(TEXT("function"), Plan.ToFunction);
	To->SetStringField(TEXT("mode"), Plan.Mode);
	Inventory->SetObjectField(TEXT("to"), To);
	TArray<TSharedPtr<FJsonValue>> MapValues;
	for (const FCortexGraphRetargetPinMapping& Entry : Plan.PinMap)
	{
		TSharedPtr<FJsonObject> EntryJson = MakeShared<FJsonObject>();
		EntryJson->SetStringField(TEXT("from_pin"), Entry.FromPin);
		EntryJson->SetStringField(TEXT("to_pin"), Entry.ToPin);
		MapValues.Add(MakeShared<FJsonValueObject>(EntryJson));
	}
	Inventory->SetArrayField(TEXT("pin_map"), MapValues);
	Inventory->SetBoolField(TEXT("awaiting_approval"), Plan.bAwaitingApproval);
	Inventory->SetBoolField(TEXT("complete"), true);
	Inventory->SetNumberField(TEXT("scanned_nodes"), Plan.ScannedNodes);
	Inventory->SetNumberField(TEXT("site_count"), Plan.Sites.Num());
	int32 Blocked = 0;
	TArray<TSharedPtr<FJsonValue>> SiteValues;
	for (const FCortexGraphRetargetSite& Site : Plan.Sites)
	{
		Blocked += Site.Blocked.IsEmpty() ? 0 : 1;
		SiteValues.Add(MakeShared<FJsonValueObject>(Site.ToJson()));
	}
	Inventory->SetNumberField(TEXT("blocked_count"), Blocked);
	Inventory->SetArrayField(TEXT("sites"), SiteValues);
	return Inventory;
}

TSharedPtr<FJsonObject> FCortexGraphRetargetOps::MakeInventory(const TSharedPtr<FJsonObject>& PlanJson)
{
	if (!PlanJson.IsValid()) return nullptr;
	FCortexGraphMigrationRetargetPlan Plan;
	FCortexCommandResult PlanError;
	if (!FCortexGraphMigrationRetargetPlan::FromJson(PlanJson, Plan, PlanError)) return nullptr;
	return MakeInventory(Plan);
}
