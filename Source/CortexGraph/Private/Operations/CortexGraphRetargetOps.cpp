bool IsSameClass(const UClass* A, const UClass* B)
{
	return A != nullptr && B != nullptr && (A == B || A->GetAuthoritativeClass() == B->GetAuthoritativeClass());
}

FString ClassPathOf(const UClass* Class)
{
	return Class ? Class->GetAuthoritativeClass()->GetPathName() : FString();
}

EEdGraphPinDirection OppositeDirection(const int32 Direction)
{
	return Direction == static_cast<int32>(EGPD_Input) ? EGPD_Output : EGPD_Input;
}

FString DirectionName(const int32 Direction)
{
	return Direction == static_cast<int32>(EGPD_Output) ? TEXT("output") : TEXT("input");
}

bool ParseDirection(const FString& Name, int32& OutDirection)
{
	if (Name == TEXT("input")) { OutDirection = static_cast<int32>(EGPD_Input); return true; }
	if (Name == TEXT("output")) { OutDirection = static_cast<int32>(EGPD_Output); return true; }
	return false;
}

FString PinSignature(const UEdGraphPin& Pin)
{
	return FCortexGraphPatchOps::CanonicalPinSignature(FCortexGraphPatchOps::MakePinSignatureDescriptor(Pin));
}

/** The canonical type of one pin without its name, so a renamed pin compares by what it carries. */
FString PinTypeSignature(const UEdGraphPin& Pin)
{
	TSharedPtr<FJsonObject> Descriptor = FCortexGraphPatchOps::MakePinSignatureDescriptor(Pin);
	Descriptor->SetStringField(TEXT("name"), FString());
	return FCortexGraphPatchOps::CanonicalPinSignature(Descriptor);
}

FString NodeGuidText(const UEdGraphNode& Node)
{
	return Node.NodeGuid.ToString();
}

FString NodeSetDigest(TArray<FString> Guids)
{
	Guids.Sort();
	const FString Joined = FString::Join(Guids, TEXT("\n"));
	FTCHARToUTF8 Utf8(*Joined);
	return LexToString(FIoHash::HashBuffer(reinterpret_cast<const uint8*>(Utf8.Get()), Utf8.Length()));
}

bool LinkLess(const FCortexGraphRetargetLink& A, const FCortexGraphRetargetLink& B)
{
	return A.NodeGuid != B.NodeGuid ? A.NodeGuid < B.NodeGuid : A.Pin < B.Pin;
}

bool PinLess(const FCortexGraphRetargetPin& A, const FCortexGraphRetargetPin& B)
{
	return A.Direction != B.Direction ? A.Direction < B.Direction : A.Name < B.Name;
}

/** An input pin carries a user-authored literal the replacement has to receive. */
bool HasUserDefault(const UEdGraphPin& Pin)
{
	if (Pin.Direction != EGPD_Input || Pin.bHidden || Pin.bDefaultValueIsIgnored
		|| Pin.PinType.PinCategory == UEdGraphSchema_K2::PC_Exec)
	{
		return false;
	}
	if (Pin.DefaultObject != nullptr || !Pin.DefaultTextValue.IsEmpty())
	{
		return true;
	}
	return !Pin.DefaultValue.IsEmpty() && Pin.DefaultValue != Pin.AutogeneratedDefaultValue;
}

TArray<TSharedPtr<FJsonValue>> StringValues(const TArray<FString>& Strings)
{
	TArray<TSharedPtr<FJsonValue>> Values;
	for (const FString& String : Strings)
	{
		Values.Add(MakeShared<FJsonValueString>(String));
	}
	return Values;
}

bool ReadStrings(const TSharedPtr<FJsonObject>& Source, const TCHAR* Field, TArray<FString>& Out)
{
	const TArray<TSharedPtr<FJsonValue>>* Values = nullptr;
	if (!Source->TryGetArrayField(Field, Values) || !Values)
	{
		return false;
	}
	for (const TSharedPtr<FJsonValue>& Value : *Values)
	{
		FString String;
		if (!Value.IsValid() || !Value->TryGetString(String))
		{
			return false;
		}
		Out.Add(MoveTemp(String));
	}
	return true;
}

const FCortexGraphRetargetSite* FindSite(const TArray<FCortexGraphRetargetSite>& Sites, const FString& NodeGuid)
{
	return Sites.FindByPredicate([&NodeGuid](const FCortexGraphRetargetSite& Site) { return Site.NodeGuid == NodeGuid; });
}

const FCortexGraphRetargetPin* FindPin(const FCortexGraphRetargetSite& Site, const FString& Name, const int32 Direction)
{
	return Site.Pins.FindByPredicate([&](const FCortexGraphRetargetPin& Pin) { return Pin.Name == Name && Pin.Direction == Direction; });
}

/** The node that holds a site's links after the apply: the replacement of a message->call site, the node itself otherwise. */
FString SiteNodeAfter(const FCortexGraphRetargetSite& Site)
{
	return Site.ReplacementGuid.IsEmpty() ? Site.NodeGuid : Site.ReplacementGuid;
}

/**
 * The link set a replacement pin must hold after the apply: the reviewed links of the pin that maps onto it, with every far
 * endpoint that is itself a site translated to that site's replacement node and mapped pin.
 */
bool ExpectedLinks(
	const TArray<FCortexGraphRetargetSite>& Sites,
	const FCortexGraphRetargetPin& Pin,
	TSet<FString>& OutKeys,
	FString& OutFailure)
{
	for (const FCortexGraphRetargetLink& Link : Pin.Links)
	{
		const int32 FarDirection = static_cast<int32>(OppositeDirection(Pin.Direction));
		if (const FCortexGraphRetargetSite* FarSite = FindSite(Sites, Link.NodeGuid))
		{
			const FCortexGraphRetargetPin* FarPin = FindPin(*FarSite, Link.Pin, FarDirection);
			if (!FarPin || FarPin->MapsTo.IsEmpty())
			{
				OutFailure = FString::Printf(TEXT("the reviewed link target %s.%s has no replacement pin"), *Link.NodeGuid, *Link.Pin);
				return false;
			}
			OutKeys.Add(FCortexGraphRetargetOps::LinkKey(SiteNodeAfter(*FarSite), FarPin->MapsTo, FarDirection));
		}
		else
		{
			OutKeys.Add(FCortexGraphRetargetOps::LinkKey(Link.NodeGuid, Link.Pin, FarDirection));
		}
	}
	return true;
}

/** Transient planning Blueprint that models the replacement nodes without touching the asset. */
struct FRetargetModel
{
	UBlueprint* Blueprint = nullptr;
	UEdGraph* Graph = nullptr;
	~FRetargetModel()
	{
		if (Blueprint)
		{
			Blueprint->MarkAsGarbage();
		}
	}
};

bool BuildModel(UBlueprint* Live, FRetargetModel& Out)
{
	Out.Blueprint = NewObject<UBlueprint>(GetTransientPackage(), NAME_None, RF_Transient);
	Out.Blueprint->ParentClass = Live->ParentClass;
	Out.Blueprint->GeneratedClass = Live->GeneratedClass;
	Out.Blueprint->SkeletonGeneratedClass = Live->SkeletonGeneratedClass;
	Out.Graph = NewObject<UEdGraph>(Out.Blueprint, NAME_None, RF_Transient);
	Out.Graph->Schema = UEdGraphSchema_K2::StaticClass();
	Out.Blueprint->FunctionGraphs.Add(Out.Graph);
	return true;
}

/** The replacement node of one site, with its pins allocated, or null when the site's class is not rewritten. */
UEdGraphNode* BuildModelNode(
	FRetargetModel& Model,
	const UEdGraphNode& Old,
	const FString& Kind,
	const FString& Mode,
	UClass* ToOwner,
	const FString& ToFunction)
{
	UEdGraphNode* Node = nullptr;
	if (Kind == KindCast)
	{
		UK2Node_DynamicCast* const NewCast = NewObject<UK2Node_DynamicCast>(Model.Graph, NAME_None, RF_Transient);
		NewCast->TargetType = ToOwner;
		if (const UK2Node_DynamicCast* const OldCast = Cast<UK2Node_DynamicCast>(&Old))
		{
			NewCast->SetPurity(OldCast->IsNodePure());
		}
		Node = NewCast;
	}
	else
	{
		UK2Node_CallFunction* Call = nullptr;
		if (Kind == KindMessage && Mode == ModeMessage)
		{
			Call = NewObject<UK2Node_Message>(Model.Graph, NAME_None, RF_Transient);
		}
		else
		{
			Call = NewObject<UK2Node_CallFunction>(Model.Graph, NAME_None, RF_Transient);
		}
		Call->FunctionReference.SetExternalMember(FName(*ToFunction), ToOwner);
		Node = Call;
	}
	Node->CreateNewGuid();
	Model.Graph->AddNode(Node, false, false);
	Node->AllocateDefaultPins();
	return Node;
}

FString CounterpartName(
	const FCortexGraphMigrationRetargetPlan& Plan,
	const FString& Kind,
	const UEdGraphPin& Old,
	const UEdGraphNode& Model,
	const UClass* FromOwner)
{
	const int32 Direction = static_cast<int32>(Old.Direction);
	if (Kind == KindCast)
	{
		const bool bCastResult = Old.Direction == EGPD_Output && IsSameClass(Cast<UClass>(Old.PinType.PinSubCategoryObject.Get()), FromOwner);
		if (bCastResult)
		{
			const UK2Node_DynamicCast* const ModelCast = Cast<UK2Node_DynamicCast>(&Model);
			const UEdGraphPin* const Result = ModelCast ? ModelCast->GetCastResultPin() : nullptr;
			return Result ? Result->PinName.ToString() : FString();
		}
		const UEdGraphPin* const Same = Model.FindPin(Old.PinName, Old.Direction);
		return Same ? Old.PinName.ToString() : FString();
	}
	FString Mapped = Old.PinName.ToString();
	for (const FCortexGraphRetargetPinMapping& Entry : Plan.PinMap)
	{
		if (Entry.FromPin == Mapped)
		{
			Mapped = Entry.ToPin;
			break;
		}
	}
	const UEdGraphPin* const Counterpart = Model.FindPin(FName(*Mapped), static_cast<EEdGraphPinDirection>(Direction));
	return Counterpart ? Mapped : FString();
}

